export function seedNotifLogs(): NotificationLog[] {
  return LOG_SEED.map(
    (
      [
        recipient,
        appId,
        templateName,
        channel,
        status,
        priority,
        hours,
        message,
      ],
      i,
    ) => ({
      id: `nlog-${i + 1}`,
      recipient,
      appId,
      templateName,
      channel,
      status,
      priority,
      sentAt: hoursAgo(hours),
      message,
    }),
  );
}

